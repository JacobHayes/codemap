//! Roles from path conventions. In-file evidence overrides these line by line (see `syntax`).

use codemap_lang::{Language, Role};

const VENDORED_DIRS: &[&str] = &[
    "vendor",
    "vendored",
    "third_party",
    "third-party",
    "node_modules",
];
/// Build output committed in source, and test snapshots.
const GENERATED_DIRS: &[&str] = &["dist", "__snapshots__"];
/// Lock files, test snapshots and golden files (written by tools, compared by tests), and
/// source maps.
const GENERATED_EXTENSIONS: &[&str] = &["lock", "snap", "golden", "map"];
/// Minified bundles.
const GENERATED_SUFFIXES: &[&str] = &[
    ".min.js",
    ".min.css",
    ".min.mjs",
    ".pb.go",
    ".pb.gw.go",
    "_gen.go",
    ".gen.go",
    "_generated.go",
];
const TEST_DIRS: &[&str] = &[
    "tests",
    "test",
    "__tests__",
    "spec",
    "specs",
    "fixtures",
    "testdata",
    "e2e",
];
const BENCH_DIRS: &[&str] = &["benches", "bench", "benchmarks"];
const EXAMPLE_DIRS: &[&str] = &["examples", "example"];
const SCRIPT_DIRS: &[&str] = &["scripts", "script"];
const SCRIPT_EXTENSIONS: &[&str] = &["sh", "bash", "zsh", "ps1"];
const DOCS_DIRS: &[&str] = &["docs", "doc"];
const DOCS_EXTENSIONS: &[&str] = &["md", "mdx", "rst", "adoc", "txt"];
const CONFIG_EXTENSIONS: &[&str] = &[
    "toml",
    "yaml",
    "yml",
    "json",
    "jsonc",
    "ini",
    "cfg",
    "conf",
    "env",
    "properties",
];
const LOCK_FILES: &[&str] = &[
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "go.sum",
    "go.work.sum",
];
/// Manifests with no config extension.
const CONFIG_FILES: &[&str] = &["go.mod", "go.work"];
/// Markers of generated code, matched case-insensitively in the first lines of a file.
const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "do not edit",
    "code generated",
    "auto-generated",
    "autogenerated",
];
/// Generators put their marker in the header; later lines are the file's own.
const GENERATED_HEAD_LINES: usize = 5;

/// How far into a file a language's generated-code header is looked for.
const GENERATED_HEADER_LINES_MAX: usize = 100;

/// The role a file has by where it lives and what its first lines say.
#[must_use]
pub fn role_for_path(path: &str, language: Option<&Language>, text: &str) -> Role {
    let mut parts: Vec<&str> = path.split('/').collect();
    let file = parts.pop().unwrap_or("");
    let (stem, extension) = file
        .rsplit_once('.')
        .map_or((file, String::new()), |(stem, extension)| {
            (stem, extension.to_ascii_lowercase())
        });
    let in_dir = |names: &[&str]| parts.iter().any(|part| names.contains(part));
    let extension = extension.as_str();

    if in_dir(VENDORED_DIRS) {
        Role::Vendored
    } else if in_dir(GENERATED_DIRS)
        || GENERATED_EXTENSIONS.contains(&extension)
        || GENERATED_SUFFIXES
            .iter()
            .any(|suffix| file.to_ascii_lowercase().ends_with(suffix))
        || LOCK_FILES.contains(&file)
        || has_generated_marker(text)
        || language.is_some_and(|language| has_generated_header(language, text))
    {
        Role::Generated
    } else if in_dir(TEST_DIRS) || is_test_file(file, stem, language) {
        Role::Test
    } else if in_dir(BENCH_DIRS) {
        Role::Bench
    } else if in_dir(EXAMPLE_DIRS) {
        Role::Example
    } else if in_dir(SCRIPT_DIRS) || SCRIPT_EXTENSIONS.contains(&extension) {
        Role::Script
    } else if in_dir(DOCS_DIRS) || DOCS_EXTENSIONS.contains(&extension) {
        Role::Docs
    } else if CONFIG_EXTENSIONS.contains(&extension) || CONFIG_FILES.contains(&file) {
        Role::Config
    } else {
        Role::Prod
    }
}

/// A file that only declares types for code written elsewhere (`.d.ts`, `.pyi`): its comments
/// are its documentation, not commentary on logic.
#[must_use]
pub fn is_declaration_file(path: &str) -> bool {
    let path = path.to_ascii_lowercase();
    [".d.ts", ".d.mts", ".d.cts", ".pyi"]
        .iter()
        .any(|suffix| path.ends_with(suffix))
}

fn is_test_file(file: &str, stem: &str, language: Option<&Language>) -> bool {
    let by_language = language.is_some_and(|language| {
        language
            .test_stem_prefixes
            .iter()
            .any(|prefix| stem.starts_with(prefix))
            || language
                .test_stem_suffixes
                .iter()
                .any(|suffix| stem.ends_with(suffix))
    });
    by_language
        || matches!(stem, "conftest" | "test" | "tests")
        || file.contains(".test.")
        || file.contains(".spec.")
}

/// A language's own generated-file line, anywhere before its header ends, often below a licence
/// header too long for the marker window. Only that language's files are searched: others may
/// carry such a line inside a string.
fn has_generated_header(language: &Language, text: &str) -> bool {
    language.generated_header.as_ref().is_some_and(|header| {
        text.lines()
            .take(GENERATED_HEADER_LINES_MAX)
            .take_while(|line| !line.starts_with(header.ends_before))
            .any(|line| {
                line.starts_with(header.line_prefix)
                    && line.trim_end().ends_with(header.line_suffix)
            })
    })
}

fn has_generated_marker(text: &str) -> bool {
    text.lines().take(GENERATED_HEAD_LINES).any(|line| {
        let line = line.to_ascii_lowercase();
        GENERATED_MARKERS.iter().any(|marker| line.contains(marker))
    })
}
